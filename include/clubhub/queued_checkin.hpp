#pragma once
#include <chrono>
#include <optional>
#include <string>
#include <vector>
#include <algorithm>
#include <utility>
namespace clubhub {
enum class SyncState {
    Pending,
    Sent,
    Accepted,
    Rejected
};
// One check-in recorded on an organiser's phone while offline.
struct QueuedCheckIn {
    std::string localId;       // Unique UUID generated by the device
    std::string deviceId;
    std::string eventId;
    std::string studentId;
    std::chrono::sys_seconds scannedAt;
    unsigned int attempts = 0;
    SyncState state = SyncState::Pending;
    std::optional<std::string> rejectReason;
};
class CheckInQueue {
public:
    // Add a check-in to the queue.
    // Return false if this student is already queued for this event.
    bool enqueue(QueuedCheckIn item) {
        for (const auto& existing : items_) {
            if (existing.eventId == item.eventId &&
                existing.studentId == item.studentId) {
                return false;
            }
        }
        items_.push_back(std::move(item));
        return true;
    }
    // Return all check-ins waiting to synchronise.
    std::vector<QueuedCheckIn> pending() const {
        std::vector<QueuedCheckIn> result;
        for (const auto& item : items_) {
            if (item.state == SyncState::Pending ||
                item.state == SyncState::Sent) {
                result.push_back(item);
            }
        }
        return result;
    }
    // Mark a check-in as accepted by the server.
    void markAccepted(const std::string& localId) {
        for (auto& item : items_) {
            if (item.localId == localId) {
                item.state = SyncState::Accepted;
                item.rejectReason.reset();
                return;
            }
        }
    }
    // Mark a check-in as rejected by the server.
    void markRejected(const std::string& localId,std::string reason) {
        for (auto& item : items_) {
            if (item.localId == localId) {
                item.state = SyncState::Rejected;
                item.rejectReason = std::move(reason);
                return;
            }
        }
    }
private:
    std::vector<QueuedCheckIn> items_;
};
} // namespace clubhub